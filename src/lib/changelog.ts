  /**
   * どう使うか（どこを開く / 何を押す / どうなれば成功か）。
   * 画面で使える変化が無いリリースでは共有ワークフローが生成しないため、その場合は持たせない
   * （空配列ではなく未定義にする。画面は `usage` が無いときに枠ごと出さない）。
   */
